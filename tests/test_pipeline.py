class TestTransforms(unittest.TestCase):
    def test_round_trip(self):
        img = torch.randn(3, N, N, dtype=torch.float64)
        self.assertLess((func.uv_to_image(func.image_to_uv(img)).real - img).abs().max().item(), 1e-12)

    def test_beam_centre_source_has_zero_phase(self):
        pt = torch.zeros(N, N, dtype=torch.float64)
        pt[N // 2, N // 2] = 1.0
        uv = func.image_to_uv(pt)
        self.assertLess(uv.angle().abs().max().item(), 1e-12)
        self.assertTrue(torch.allclose(uv.abs(), torch.full_like(uv.abs(), 1.0 / N)))

    def test_all_fourier_transforms_are_ortho(self):
        # energy conservation (Parseval): every (i)(r)fft(2/n) call in src/, scripts/, fisher/ and
        # the notebooks passes norm="ortho"
        import json
        import re
        call = re.compile(r"fft\.(?:i?r?fftn?2?)\(")
        sources = [(f, f.read_text()) for d in ("src", "scripts", "fisher") for f in (ROOT / d).glob("*.py")]
        for f in [*(ROOT / "notebooks").glob("*.ipynb"), *(ROOT / "fisher").glob("*.ipynb")]:
            cells = json.loads(f.read_text())["cells"]
            sources += [(f, "".join(c["source"])) for c in cells if c["cell_type"] == "code"]
        for f, text in sources:
            code = "\n".join(line.split("#")[0] for line in text.split("\n"))   # drop comments
            for m in call.finditer(code):
                depth, k = 1, m.end()
                while depth and k < len(code):                    # the call's full argument list
                    depth += {"(": 1, ")": -1}.get(code[k], 0)
                    k += 1
                with self.subTest(file=f.name, call=code[m.start():k][:60]):
                    self.assertRegex(code[m.start():k], r"norm\s*=\s*[\"']ortho[\"']")

    def test_uv_tracks_are_fft_ordered(self):
        # most integrations sit near DC = pixel (0, 0), almost none near (N/2, N/2)
        p = model.padded
        x, y, t = p[:, 0].long(), p[:, 1].long(), p[:, 2]
        dist = lambda a: torch.minimum(a, N - a)
        near_dc = (t * ((dist(x) < 8) & (dist(y) < 8))).sum() / t.sum()
        near_mid = (t * (((x - N // 2).abs() < 8) & ((y - N // 2).abs() < 8))).sum() / t.sum()
        self.assertGreater(near_dc.item(), 0.2)
        self.assertLess(near_mid.item(), 1e-3)


class TestSkyModel(unittest.TestCase):
    def test_hermitian_noise_unit_power_on_every_mode(self):
        n = func.generate_hermitian_noise(3000, N, N, "cpu")
        kept = torch.fft.rfft2(torch.fft.irfft2(n, s=(N, N), norm="ortho"), norm="ortho")
        P = (kept.abs() ** 2).mean(0)
        for name, sel in [("kx=0", P[1:N // 2, 0]), ("Nyquist", P[1:N // 2, -1]),
                          ("interior", P[1:N // 2, 1:-1])]:
            with self.subTest(column=name):
                self.assertAlmostEqual(sel.mean().item(), 1.0, delta=0.03)

    def test_measured_pk_matches_analytic(self):
        torch.manual_seed(0)
        B = 300
        pw = torch.tensor(settings.TRUE_PW).repeat(B, 1)
        A, n1, n2, kb = 10 ** pw[:, 0], pw[:, 1], pw[:, 2], 10 ** pw[:, 3]
        delta = model.density_sim.sample_field(A.to(DEV), n1.to(DEV), n2.to(DEV), kb.to(DEV))
        k, pk, _ = model.pk_measurer(delta)
        ana = func.power_spectrum_2d(k.cpu(), A[:1], n1[:1], n2[:1], kb[:1]).reshape(-1)
        ratio = (pk.mean(0).cpu() / ana).numpy()
        self.assertAlmostEqual(float(np.nanmedian(ratio)), 1.0, delta=0.03)

    def test_brightness_temperature(self):
        delta = torch.randn(2, N, N, device=DEV) * 0.1
        Tb = model.brightness(delta)
        # z = 9, T_S >> T_CMB, Planck 2018 (settings.py)
        T0 = func.mean_brightness_temperature(settings.REDSHIFT, settings.HUBBLE_H, settings.OMEGA_B,
                                              settings.OMEGA_M, settings.HELIUM_Y)
        self.assertAlmostEqual(T0, 26.602, places=3)
        self.assertTrue(torch.allclose(Tb, T0 * (1 + delta), atol=1e-4))
        # Furlanetto et al. (2006) approximation, 27 mK at Ω_b h² = 0.023, Ω_m h² = 0.15: the exact
        # formula gives 26.93 mK there (Y_p = 0.24), and agrees with the approximation to 1 % for Planck 2018
        ref = func.mean_brightness_temperature(9.0, 0.7, 0.023 / 0.49, 0.15 / 0.49, 0.24)
        self.assertAlmostEqual(ref / 27.0, 1.0, delta=0.005)
        hh = settings.HUBBLE_H ** 2
        approx = 27.0 * (settings.OMEGA_B * hh / 0.023) * np.sqrt(
            0.15 / (settings.OMEGA_M * hh) * (1 + settings.REDSHIFT) / 10)
        self.assertAlmostEqual(T0 / approx, 1.0, delta=0.01)


class TestUVPath(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        torch.manual_seed(1)
        pw = np.tile(np.array([settings.TRUE_PW], np.float32), (2, 1))
        df = model.DensityFromPw().simulate_batch(2, pw)
        cls.image = model.SkyImageFromBrightness().simulate_batch(2, model.BrightnessFromDensity().simulate_batch(2, df))
        cls.uvimage = model.UVSkyFromImage().simulate_batch(2, cls.image)
        cls.sampled = to_np(model.UV_COUNT)[0] > 0                              # (S, N, N)
        unit = to_np(func.theta_to_gains(torch.zeros(1, 2 * model.N_UNKNOWN), model.KNOWN_ANT))
        cls.st_unit = model.UVTracksFromGains().simulate_batch(1, unit)

    def _x(self, stacked, uvimage):
        tracked = model.TrackedUVFromSky().simulate_batch(len(uvimage), uvimage, np.repeat(stacked, len(uvimage), 0))
        return model.NormalisedUV().simulate_batch(len(uvimage), tracked)

    def test_unit_gains_sample_the_sky_exactly(self):
        x = self._x(self.st_unit, self.uvimage)
        expected = self.uvimage[:, None] * self.sampled[None]
        self.assertLess(np.abs(x - expected).max(), 1e-4)

    def test_x_hermitian_and_obsx_real(self):
        gains = true_gains_np()
        x = self._x(model.UVTracksFromGains().simulate_batch(1, gains), self.uvimage)
        self.assertLess(max_hermitian_error(x), 1e-4)
        full = to_np(func.uv_to_image(torch.tensor(x)))
        self.assertLess(np.abs(full.imag).max() / np.abs(full.real).max(), 1e-5)

    def test_dirty_image_dc_free_and_aligned(self):
        obsx = model.DirtyImageFromUV().simulate_batch(2, self._x(self.st_unit, self.uvimage))
        self.assertLess(np.abs(obsx.mean(axis=(-2, -1))).max(), 1e-4)
        # unit gains: the dirty image is the sky minus mean, low-pass filtered — highly correlated
        sky0 = self.image - self.image.mean(axis=(-2, -1), keepdims=True)
        corr = np.corrcoef(sky0[0].ravel(), obsx[0, 0].ravel())[0, 1]
        self.assertGreater(corr, 0.9)

    def test_psf_peaks_at_beam_centre(self):
        pt = np.zeros((1, N, N), np.float32)
        pt[0, N // 2, N // 2] = 1
        psf = model.DirtyImageFromUV().simulate_batch(1, self._x(self.st_unit, model.UVSkyFromImage().simulate_batch(1, pt)))
        for s in range(psf.shape[1]):
            with self.subTest(subset=s):
                self.assertEqual(np.unravel_index(psf[0, s].argmax(), (N, N)), (N // 2, N // 2))

    def test_pk_obs_unit_gains_bounded_by_sky_pk(self):
        # with unit gains, pk_obs is the sky P(k) with unsampled modes set to 0: never above it,
        # and equal to it in fully sampled bins
        obsx = model.DirtyImageFromUV().simulate_batch(2, self._x(self.st_unit, self.uvimage))
        pk_obs = model.PkFromDirtyImage().simulate_batch(2, obsx)
        _, pk_sky, _ = model.pk_measurer(torch.tensor(self.image, device=DEV))
        ratio = pk_obs[0] / to_np(pk_sky)[0][None]
        self.assertLessEqual(np.nanmax(ratio), 1.0 + 1e-3)
        self.assertGreater(np.nanmax(ratio), 0.99)        # fully sampled bins exist


class TestThermalNoise(unittest.TestCase):
    def test_uv_noise_hermitian_scaled_and_masked(self):
        with _NoiseOverride(2.0):
            noise = model.ThermalNoiseUV().simulate_batch(400, np.zeros((400, N, N), np.complex64))
        count = to_np(model.UV_COUNT)[0]
        self.assertLess(max_hermitian_error(noise), 1e-4)
        self.assertEqual(np.abs(noise[:, count == 0]).max(), 0.0)
        m = count > 0
        self.assertAlmostEqual(((np.abs(noise) ** 2).mean(0)[m] * count[m]).mean(), 4.0, delta=0.05)

    def test_noise_is_zero_at_zero_noise_std(self):
        with _NoiseOverride(0.0):
            noise = model.ThermalNoiseUV().simulate_batch(2, np.zeros((2, N, N), np.complex64))
        self.assertEqual(np.abs(noise).max(), 0.0)

    def test_noise_std_argument_overrides_module(self):
        with _NoiseOverride(5.0):
            uv = model.ThermalNoiseUV(noise_std=0.0).simulate_batch(2, np.zeros((2, N, N), np.complex64))
            V = model.ReferenceVisFromGains(noise_std=0.0).simulate_batch(1, true_gains_np())
        self.assertEqual(np.abs(uv).max(), 0.0)
        g = func.gains_to_complex(torch.tensor(true_gains_np()))[0].to(DEV)
        np.testing.assert_allclose(V[0], to_np(g[:, None] * model.S_REF * g.conj()[None, :]), atol=1e-7)

    def test_reference_noise_per_baseline(self):
        D = model.sky_matrix
        with _NoiseOverride(1.0):
            V = model.ReferenceVisFromGains().simulate_batch(300, np.repeat(true_gains_np(), 300, 0))
        g = func.gains_to_complex(torch.tensor(true_gains_np()))[0].to(DEV)
        signal = to_np(g[:, None] * model.S_REF * g.conj()[None, :])
        N_ = V - signal[None]
        i, j, cnt = to_np(D.i_idx), to_np(D.j_idx), to_np(D.counts)
        self.assertLess(np.abs(N_ - N_.conj().transpose(0, 2, 1)).max(), 1e-5)
        self.assertLess(np.abs(N_[:, np.arange(model.NANT), np.arange(model.NANT)]).max(), 1e-6)
        self.assertLess(np.abs(N_[:, i[cnt == 0], j[cnt == 0]]).max(), 1e-6)
        obs = cnt > 0
        self.assertAlmostEqual(((np.abs(N_[:, i[obs], j[obs]]) ** 2).mean(0) * cnt[obs]).mean(), 1.0, delta=0.03)


class TestUnits(unittest.TestCase):
    def test_round_trip_keeps_dtype(self):
        x = torch.randn(2, 3, dtype=torch.complex64, device=DEV)
        for domain in ("image", "uv"):
            y = func.jansky_to_mK(func.mK_to_jansky(x, domain), domain)
            self.assertEqual((y.dtype, y.device), (x.dtype, x.device))
            np.testing.assert_allclose(to_np(y), to_np(x), rtol=1e-6)

    def test_point_source_of_one_jansky(self):
        # 1 Jy in the beam-centre pixel: every visibility of a point source equals its flux
        img = torch.zeros(1, N, N, dtype=torch.float64)
        img[0, N // 2, N // 2] = func.jansky_to_mK(1.0, "image")
        vis_jy = func.mK_to_jansky(func.image_to_uv(img), "uv")
        np.testing.assert_allclose(to_np(vis_jy.abs()), 1.0, rtol=1e-10)

    def test_domains_differ_by_n(self):
        self.assertAlmostEqual(func.mK_per_jansky("image") / func.mK_per_jansky("uv"), N, places=6)
        with self.assertRaises(ValueError):
            func.mK_per_jansky("visibility")

    def test_planck_values(self):
        # Planck 2018 (settings.py), z = 9: D_c = 9401 Mpc, 1 Jy per 4 Mpc pixel = 8.911e6 mK
        # (notebooks/noise.ipynb derives the same numbers)
        self.assertAlmostEqual(func.comoving_distance(settings.REDSHIFT), 9401, delta=1)
        self.assertAlmostEqual(func.mK_per_jansky("image") / 8.911e6, 1.0, places=3)

    def test_noise_std_in_mK_for_the_whole_observation(self):
        # one 30 s integration (in NOISE_UNIT) → mK, then / sqrt(N_DAYS) for the repeated 4 h track
        per_30s = (settings.NOISE_STD if settings.NOISE_UNIT == "mK"
                   else func.jansky_to_mK(settings.NOISE_STD, "uv", model.config))
        self.assertEqual(model.NOISE_STD_30S, per_30s)
        self.assertAlmostEqual(model.NOISE_STD, per_30s / np.sqrt(settings.N_DAYS), delta=1e-12 * (1 + per_30s))
        self.assertEqual(settings.T_OBS_H, settings.N_DAYS * settings.TOTAL_TIME_H)


class TestReferencePath(unittest.TestCase):
    def test_baselines_ij_and_ji_tracked_separately(self):
        # an arbitrary (non-Hermitian) UV map: S[j, i] must be the mean along the MIRRORED track
        # (−u) of baseline (i, j), computed on its own — not conj(S[i, j])
        D = model.sky_matrix
        gen = torch.Generator(device="cpu").manual_seed(0)
        uv = torch.randn(1, N, N, dtype=torch.complex64, generator=gen).to(DEV)
        S = to_np(D(uv))[0]
        uvf, t = to_np(uv[0]).reshape(-1), to_np(D.t)
        y, x = to_np(model.padded[:, 1]).astype(int), to_np(model.padded[:, 0]).astype(int)
        mirror = ((-y) % N) * N + (-x) % N
        cnt = t.sum(-1)
        obs = cnt > 0
        expect_ji = (uvf[mirror] * t).sum(-1)[obs] / cnt[obs]
        i, j = to_np(D.i_idx)[obs], to_np(D.j_idx)[obs]
        np.testing.assert_allclose(S[j, i], expect_ji, rtol=1e-5, atol=1e-6)
        self.assertGreater(np.abs(S[j, i] - np.conj(S[i, j])).max(), 0.1)        # not forced Hermitian

    def test_real_sky_gives_hermitian_s(self):
        S = to_np(model.sky_matrix(func.image_to_uv(torch.randn(1, N, N, device=DEV))))[0]
        self.assertLess(np.abs(S - S.conj().T).max() / np.abs(S).max(), 1e-5)

    @classmethod
    def setUpClass(cls):
        D = model.sky_matrix
        cls.i, cls.j, cls.cnt = to_np(D.i_idx), to_np(D.j_idx), to_np(D.counts)
        cls.obs = cls.cnt > 0
        cls.S = to_np(model.S_REF)

    def test_s_ref_matches_calibrator_definition(self):
        cal = settings.CALIBRATOR_FLUX * func.gaussian_2d(N, settings.CALIBRATOR_SIGMA, DEV)
        S = model.sky_matrix(func.image_to_uv(cal[None]))[0]
        self.assertTrue(torch.equal(S, model.S_REF))

    def test_s_ref_flat_amplitude_zero_phase(self):
        Sv = self.S[self.i, self.j][self.obs]
        cal = settings.CALIBRATOR_FLUX * func.gaussian_2d(N, settings.CALIBRATOR_SIGMA, "cpu")
        F = func.image_to_uv(cal).abs()
        self.assertGreaterEqual(np.abs(Sv).min(), F.min().item() * (1 - 1e-5))
        self.assertLessEqual(np.abs(Sv).max(), F.max().item() * (1 + 1e-5))
        self.assertLess(np.abs(np.angle(Sv)).max(), 1e-6)

    def test_s_ref_zero_where_unobserved(self):
        self.assertEqual(np.abs(self.S[self.i[~self.obs], self.j[~self.obs]]).max(), 0.0)
        self.assertEqual(np.abs(np.diag(self.S)).max(), 0.0)

    def test_v_ref_is_g_s_gH(self):
        gains = true_gains_np()
        with _NoiseOverride(0.0):
            V = model.ReferenceVisFromGains().simulate_batch(1, gains)[0]
        expected = to_np(func.visibilities_from_gains(torch.tensor(gains, device=DEV), model.S_REF[None]))[0]
        self.assertLess(np.abs(V - expected).max(), 1e-7)

    def test_gains_recoverable_from_first_row(self):
        gains = true_gains_np()
        with _NoiseOverride(0.0):
            V = model.ReferenceVisFromGains().simulate_batch(1, gains)[0]
        g = to_np(func.gains_to_complex(torch.tensor(gains)))[0]
        row = np.where(self.obs[self.i == 0])[0] + 1           # antennas j with (0, j) observed
        g_rec = np.conj(V[0, row] / self.S[0, row])
        self.assertLess(np.abs(g_rec - g[row]).max(), 1e-5)


class TestEmbeddings(unittest.TestCase):
    def test_first_row_and_upper_sizes(self):
        import embedding
        with _NoiseOverride(0.0):
            V = model.ReferenceVisFromGains().simulate_batch(2, np.repeat(true_gains_np(), 2, 0))
        cnt = to_np(model.sky_matrix.counts)
        i = to_np(model.sky_matrix.i_idx)
        n_row = int((cnt[i == 0][:model.N_UNKNOWN] > 0).sum())   # baselines (0, j), j unknown
        n_all = int((cnt > 0).sum())
        self.assertEqual(n_row, model.N_UNKNOWN)                    # every unknown gain is seen
        self.assertEqual(embedding.VRefFirstRowEmbedding()(V).shape, (2, 2 * n_row))
        self.assertEqual(embedding.VRefUpperTriEmbedding()(V).shape, (2, 2 * n_all))

    def test_first_row_ignores_known_antennas(self):
        # baselines to known antennas are constant (S_ref) and must not reach the Stage-1 network:
        # their CPU/GPU rounding difference, whitened by a zero training std, broke output/run_01
        import embedding
        with _NoiseOverride(0.0):
            V = model.ReferenceVisFromGains().simulate_batch(2, np.repeat(true_gains_np(), 2, 0))
        emb = embedding.VRefFirstRowEmbedding()
        out = emb(V)
        V2 = V.copy()
        V2[:, 0, 1 + model.N_UNKNOWN:] *= 1.5
        self.assertTrue(torch.equal(emb(V2), out))

    def test_pk_embedding_forward(self):
        import embedding
        pk = np.abs(np.random.default_rng(0).normal(size=(4, settings.N_SUBSETS, 50))).astype(np.float32) + 1e-3
        V = np.random.default_rng(1).normal(size=(4, model.NANT, model.NANT)).astype(np.complex64)
        net = embedding.PkVRefEmbedding(hidden_dim=16, feat_dim=8).to(embedding.device)   # as falcon does
        out = net(pk, V)
        self.assertEqual(out.shape[0], 4)
        self.assertTrue(torch.isfinite(out).all())



class TestDataFreshness(unittest.TestCase):
    """data/*.npy must come from the current code and settings (re-run scripts/gen_mock_data.py)."""
    HINT = "data/ is stale: run `python scripts/gen_mock_data.py`"

    def load(self, name):
        path = settings.DATA_DIR / f"{name}.npy"
        if not path.exists():
            self.fail(f"missing {path.name}; {self.HINT}")
        return np.load(path)

    def test_s_ref_file(self):
        self.assertLess(np.abs(self.load("S_ref") - to_np(model.S_REF)).max(), 1e-7, self.HINT)

    def test_truth_files(self):
        np.testing.assert_array_equal(self.load("true_z"), to_np(settings.true_z(model.N_UNKNOWN)), self.HINT)
        np.testing.assert_allclose(self.load("true_pw"), np.array([settings.TRUE_PW]), err_msg=self.HINT)

    def test_v_ref_obs_matches_simulator(self):
        if settings.NOISE_STD != 0:
            self.skipTest("noisy V_ref_obs cannot be recomputed exactly")
        with _NoiseOverride(0.0):
            V = model.ReferenceVisFromGains().simulate_batch(1, true_gains_np())[0]
        self.assertLess(np.abs(self.load("V_ref_obs") - V).max(), 1e-6, self.HINT)

    def test_observed_shapes_match_simulator(self):
        self.assertEqual(self.load("pk_obs").shape, (settings.N_SUBSETS, 50), self.HINT)
        self.assertEqual(self.load("V_ref_obs").shape, (model.NANT, model.NANT), self.HINT)
        self.assertEqual(self.load("obsx_obs").dtype, np.float32, self.HINT)


